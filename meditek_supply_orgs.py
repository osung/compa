def include_map():
    """{과제수행기관명: 공급기관명}. 같은 기관이 두 공급기관에 걸리면 ' / ' 로 잇는다."""
    rev = {}
    for sup, (_memo, _probe, orgs) in SUPPLY_ORGS.items():
        for o in orgs:
            rev[o] = f"{rev[o]} / {sup}" if o in rev else sup
    return rev


def audit(all_org_names):
    """코퍼스의 기관명 집합과 대조 → (없는 포함대상, 분류 안 된 PROBE 적중 이름).

    두 번째가 비어 있지 않으면 코퍼스에 새 표기가 생긴 것이다. 조용히 빠지거나 섞이지
    않도록 호출측에서 드러내고 사람이 SUPPLY_ORGS 에 반영해야 한다.
    """
    import re
    have = set(all_org_names)
    missing, unclassified = {}, {}
    for sup, (_memo, probe, orgs) in SUPPLY_ORGS.items():
        miss = [o for o in orgs if o not in have]
        if miss:
            missing[sup] = miss
        hit = {o for o in have if o and re.search(probe, o, re.I)}
        rest = sorted(hit - set(orgs))
        if rest:
            unclassified[sup] = rest
    return missing, unclassified
